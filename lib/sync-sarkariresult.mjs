import cloudscraper from "cloudscraper";
import * as cheerio from "cheerio";
import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_FILE = resolve(__dirname, "..", "data", "scraped-data.ts");
const POSTS_DIR = resolve(__dirname, "..", "data", "posts");

function loadData() {
  const raw = readFileSync(DATA_FILE, "utf8");
  const jsonStr = raw
    .replace(/^\/\/.*[\r\n]+/, "")
    .replace(/^export const scrapedData = /, "")
    .replace(/\s*as const\s*;\s*$/, "")
    .replace(/;\s*$/, "");
  return JSON.parse(jsonStr);
}

function saveData(data) {
  const ts = `// Auto-generated by sync-sarkariresult - DO NOT EDIT\nexport const scrapedData = ${JSON.stringify(data, null, 2)};\n`;
  writeFileSync(DATA_FILE, ts, "utf8");
}

function sanitizeSlug(s) {
  return s.replace(/[<>:"/\\|?*]+/g, "-").replace(/-+/g, "-").replace(/^-+|-+$/g, "") || "post";
}

function fetchHtml(url) {
  return cloudscraper({ uri: url, method: "GET" });
}

function isFutureDate(dateStr) {
  if (!dateStr) return false;
  const cleaned = dateStr.replace(/\s*\|.*$/, "").trim();
  const m = cleaned.match(/^(\d{1,2})\s+(January|February|March|April|May|June|July|August|September|October|November|December)\s+(\d{4})$/i);
  if (!m) return false;
  const months = { january: 0, february: 1, march: 2, april: 3, may: 4, june: 5, july: 6, august: 7, september: 8, october: 9, november: 10, december: 11 };
  const d = new Date(parseInt(m[3]), months[m[2].toLowerCase()], parseInt(m[1]));
  return d > new Date();
}

async function scrapeSarkariResult() {
  const html = await fetchHtml("https://www.sarkariresult.com/");
  const $ = cheerio.load(html);

  const categoryMap = { result: "results", admitcard: "admitCards", latestjob: "latestJobs", answerkey: "answerKeys", admission: "admissions" };
  const items = [];

  $(".below-block").each((_, block) => {
    const $block = $(block);
    const heading = $block.find("h4.wp-block-heading").text().trim().toLowerCase().replace(/<\/?strong>/g, "").replace(/[^a-z]+/g, "");

    // Determine category from heading or "View More" link
    let category = "";
    const viewMore = $block.find("a.wp-block-button__link").last();
    const viewMoreText = viewMore.text().trim().toLowerCase();
    if (viewMoreText.includes("admit")) category = "admitCards";
    else if (viewMoreText.includes("answer")) category = "answerKeys";
    else if (viewMoreText.includes("admission")) category = "admissions";
    else if (viewMoreText.includes("result")) category = "results";
    else if (viewMoreText.includes("job") || viewMoreText.includes("form")) category = "latestJobs";
    else if (viewMoreText.includes("document")) category = "documents";
    else category = categoryMap[heading] || "latestJobs";

    $block.find("ul.wp-block-list li a").each((_, link) => {
      const $link = $(link);
      const title = $link.text().trim();
      let url = $link.attr("href") || "";
      if (!title || !url) return;

      // sarkariresult.com relative URLs
      if (url.startsWith("/")) url = "https://www.sarkariresult.com" + url;

      if (url.includes("#") || url === "https://www.sarkariresult.com/") return;

      const slug = url.replace(/\/$/, "").split("/").pop().replace(/\.html?$/, "") || "post-" + Date.now();

      // Extract published date from list item text if available
      const parentText = $link.parent("li").text();
      let publishedDate = "";
      const dateMatch = parentText.match(/(\d{1,2}\s+(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{4})/i);
      if (dateMatch) publishedDate = dateMatch[1];

      items.push({ title, url, category, slug, publishedDate });
    });
  });

  return items;
}

async function scrapePostDetail(url) {
  try {
    const html = await fetchHtml(url);
    const $ = cheerio.load(html);

    const title = $("h1").first().text().trim() || $("title").text().trim();
    const slug = url.replace(/\/$/, "").split("/").pop().replace(/\.html?$/, "") || "post";

    // Published date
    let publishedDate = $("meta[property='article:published_time']").attr("content") || "";
    if (publishedDate) {
      const d = new Date(publishedDate);
      if (!isNaN(d.getTime())) {
        publishedDate = d.toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });
      }
    }

    // Intro from "Short Information" or first table
    let intro = "";
    $("h3, strong, b").each((_, el) => {
      const text = $(el).text().trim().toLowerCase();
      if (text.includes("short information") || text.includes("brief information")) {
        intro = $(el).parent().next("p").text().trim() || $(el).closest("div").find("p").first().text().trim();
      }
    });
    if (!intro) intro = $(".entry-content p").first().text().trim().slice(0, 300);

    // Important dates table
    const importantDates = [];
    $("table").each((_, table) => {
      const $table = $(table);
      const rows = $table.find("tr");
      rows.each((_, row) => {
        const cells = $(row).find("td, th");
        if (cells.length >= 2) {
          const first = $(cells[0]).text().trim().toLowerCase();
          const second = $(cells[1]).text().trim();
          if (first && second && (first.includes("date") || first.includes("fee") || first.includes("age") || first.includes("exam") || !first.includes("link"))) {
            importantDates.push(`${$(cells[0]).text().trim()} : ${second}`);
          }
        }
      });
    });

    // Important links
    const importantLinks = [];
    $("table a, .entry-content a").each((_, link) => {
      const $link = $(link);
      const label = $link.text().trim();
      const href = $link.attr("href") || "";
      if (label && href && href !== "#" && !href.startsWith("javascript")) {
        importantLinks.push({ label, url: href });
      }
    });

    return { title, slug, url, category: "", publishedDate, intro, importantDates, applicationFee: [], importantLinks, fullContentHtml: "" };
  } catch {
    return null;
  }
}

async function main() {
  console.log("Loading existing data...");
  const existing = loadData();
  const existingSlugs = new Set();
  const existingUrls = new Set();

  for (const key of ["results", "admitCards", "latestJobs", "answerKeys", "documents", "admissions"]) {
    for (const item of (existing[key] || [])) {
      if (item.slug) existingSlugs.add(item.slug.toLowerCase());
      if (item.url) existingUrls.add(item.url.replace(/\/$/, ""));
    }
  }

  console.log("Fetching sarkariresult.com listings...");
  const freshItems = await scrapeSarkariResult();
  console.log(`Found ${freshItems.length} items on sarkariresult.com`);

  const newItems = [];
  for (const item of freshItems) {
    const url = item.url.replace(/\/$/, "");
    if (!existingUrls.has(url)) {
      newItems.push(item);
    }
  }

  console.log(`New items: ${newItems.length}`);

  if (newItems.length > 0) {
    mkdirSync(POSTS_DIR, { recursive: true });
    let detailCount = 0;

    for (let i = 0; i < newItems.length; i += 3) {
      const batch = newItems.slice(i, i + 3);
      const results = await Promise.allSettled(batch.map(item => scrapePostDetail(item.url)));
      for (let j = 0; j < results.length; j++) {
        const result = results[j];
        if (result.status === "fulfilled" && result.value) {
          const post = result.value;
          const slug = sanitizeSlug(post.slug);
          post.slug = slug;
          post.category = newItems[i + j].category;
          if (!post.publishedDate) post.publishedDate = newItems[i + j].publishedDate || "";

          if (!existing.posts) existing.posts = {};
          existing.posts[slug] = post;
          writeFileSync(POSTS_DIR + "/" + slug + ".json", JSON.stringify(post, null, 2), "utf8");
          detailCount++;
        }
      }
    }

    // Add new items to their respective categories
    for (const item of newItems) {
      const cat = item.category;
      if (!existing[cat]) existing[cat] = [];
      existing[cat].push(item);
    }

    existing.fetchedAt = new Date().toISOString();
    saveData(existing);
    console.log(`Added ${newItems.length} new items, scraped ${detailCount} details`);
    console.log("Updated data/scraped-data.ts");
  } else {
    console.log("No new items found. Data is already up to date.");
  }
}

main().catch((e) => { console.error("Error:", e.message); process.exit(1); });
