// ── Date helpers ──────────────────────────────────────────────────────────────
function isValidPastDate(val) {
  if (!val) return false;
  const d = new Date(val);
  return !isNaN(d.getTime()) && d.getTime() <= Date.now();
}

function preserveDates(slug, newPublishedDate) {
  const now    = new Date().toISOString();
  const oldPath = `${POSTS_DIR}/${slug}.json`;
  if (existsSync(oldPath)) {
    try {
      const old = JSON.parse(readFileSync(oldPath, "utf8"));
      const oldAt   = isValidPastDate(old.publishedAt)   ? old.publishedAt   : (isValidPastDate(old.createdAt) ? old.createdAt : null);
      const oldDate = isValidPastDate(old.publishedDate) ? old.publishedDate : null;
      if (oldAt || oldDate) {
        return {
          publishedAt:   oldAt || (oldDate ? new Date(oldDate).toISOString() : now),
          createdAt:     isValidPastDate(old.createdAt) ? old.createdAt : (oldAt || now),
          publishedDate: oldDate || (oldAt ? new Date(oldAt).toLocaleDateString("en-IN", { day:"numeric", month:"long", year:"numeric" }) : now),
          updatedAt:     now,
        };
      }
    } catch {}
  }
  // New post
  const pAt = (newPublishedDate && isValidPastDate(newPublishedDate)) ? new Date(newPublishedDate).toISOString() : now;
  return { publishedAt: pAt, createdAt: pAt, publishedDate: newPublishedDate || now, updatedAt: pAt };
}

// ── Main ──────────────────────────────────────────────────────────────────────
const __timers = new Set();

async function main() {
  const start = Date.now();
  console.log("🔄 AI Exam Result Sync — sarkariexam.com only");
  console.log("   Zero source traces · AIExamResult style content\n");

  const existing    = loadData();
  const existingUrls = new Set();
  for (const cat of CATEGORIES) {
    for (const item of (existing[cat] || [])) {
      if (item.url) existingUrls.add(item.url.replace(/\/$/, ""));
    }
  }
  if (!existing.posts) existing.posts = {};

  // ── Scrape homepage ──
  console.log("[1/3] Scraping sarkariexam.com listings...");
  let fresh;
  try {
    fresh = await scrapeListings();
  } catch (e) {
    console.error("  ❌ Failed to scrape listings:", e.message);
    process.exit(1);
  }

  // Merge new items
  const newItems = [];
  for (const cat of CATEGORIES) {
    for (const item of (fresh[cat] || [])) {
      if (isJunk(item.title, item.sourceUrl)) continue;
      const finalCat = categorize(item.title, cat);
      item.category  = finalCat;
      item.slug      = generateSlug(item.sourceUrl, item.title);
      const pubUrl   = `/post/${item.slug}`;
      if (!existingUrls.has(pubUrl)) {
        const bucket = existing[finalCat] || (existing[finalCat] = []);
        bucket.unshift({ title: item.title, url: pubUrl, category: finalCat, slug: item.slug });
        existingUrls.add(pubUrl);
        newItems.push(item);
      }
    }
  }
  console.log(`  ✓ ${newItems.length} new posts found`);

  // ── Re-scrape existing empty posts ──
  const reScrapeQueue = [];
  for (const file of readdirSync(POSTS_DIR).filter(f => f.endsWith(".json"))) {
    try {
      const p = JSON.parse(readFileSync(`${POSTS_DIR}/${file}`, "utf8"));
      const isEmpty = (!p.intro || p.intro.length < 20) && (!p.fullContentHtml || p.fullContentHtml.length < 50);
      if (isEmpty && p.url && p.url.includes("sarkariexam.com")) {
        reScrapeQueue.push({ file, sourceUrl: p.url, slug: p.slug || file.replace(".json",""), title: p.title || "", category: p.category || "latestJobs" });
      }
    } catch {}
  }
  if (reScrapeQueue.length > 0) console.log(`  ✓ ${reScrapeQueue.length} empty posts queued for re-scrape`);

  // ── Fetch details for new posts ──
  mkdirSync(POSTS_DIR, { recursive: true });
  const newSlugs = [];
  let detailCount = 0;

  console.log("\n[2/3] Fetching post details...");

  async function processItem(item) {
    const detail = await scrapeDetail(item.sourceUrl, item.title, item.category);
    if (!detail) return;

    const cat      = categorize(item.title, item.category);
    const { intro, fullContentHtml } = buildPostContent(item.title, cat, detail);
    const dates    = preserveDates(item.slug, detail.publishedDate);
    const jsonLd   = buildJsonLd(item.title, item.slug, cat, intro, detail.importantLinks);
    const seoTitle = `${item.title} | ${SITE_NAME}`;

    const post = {
      title:          item.title,
      slug:           item.slug,
      category:       cat,
      publishedDate:  dates.publishedDate,
      publishedAt:    dates.publishedAt,
      createdAt:      dates.createdAt,
      updatedAt:      dates.updatedAt,
      intro,
      importantDates: detail.importantDates,
      applicationFee: detail.applicationFee,
      importantLinks: detail.importantLinks,
      fullContentHtml,
      jsonLd,
      seoMeta: {
        title:       seoTitle,
        description: intro.slice(0, 200),
        canonical:   `${SITE_URL}/post/${item.slug}`,
      },
    };

    // Update listing item dates
    const bucket = existing[cat] || [];
    const idx    = bucket.findIndex(b => b.slug === item.slug);
    if (idx !== -1) {
      bucket[idx] = { ...bucket[idx], publishedDate: dates.publishedDate, publishedAt: dates.publishedAt };
      existing[cat] = bucket;
    }
    existing.posts[item.slug] = {
      publishedDate: dates.publishedDate,
      publishedAt:   dates.publishedAt,
      lastDate:      detail.importantDates.find(d => /last/i.test(d))?.replace(/^[^:]+:\s*/, "").trim(),
    };

    writeFileSync(`${POSTS_DIR}/${item.slug}.json`, JSON.stringify(post, null, 2), "utf8");
    newSlugs.push(item.slug);
    detailCount++;
  }

  // Batch with concurrency
  const allToProcess = [...newItems, ...reScrapeQueue];
  const overallTimer = setTimeout(() => {
    console.log(`\n  ⚠️  Detail fetch timeout (${MAX_DETAIL_TIME/1000}s) reached — saving partial results`);
  }, MAX_DETAIL_TIME);
  __timers.add(overallTimer);

  for (let i = 0; i < allToProcess.length; i += CONCURRENCY) {
    const batch   = allToProcess.slice(i, i + CONCURRENCY);
    await Promise.allSettled(batch.map(item => processItem(item).catch(() => {})));
    const pct = Math.min(100, Math.round(((i + batch.length) / allToProcess.length) * 100));
    process.stdout.write(`\r  ${Math.min(i + CONCURRENCY, allToProcess.length)}/${allToProcess.length} (${pct}%) — ${detailCount} done`);
  }
  console.log("");

  clearTimeout(overallTimer);
  __timers.delete(overallTimer);
  for (const t of __timers) clearTimeout(t);
  __timers.clear();

  // Trim each category list
  for (const cat of CATEGORIES) {
    existing[cat] = (existing[cat] || []).slice(0, 500);
  }

  // ── Save ──
  console.log("\n[3/3] Saving data...");
  saveData(existing);
  const elapsed = ((Date.now() - start) / 1000).toFixed(1);
  console.log(`✅ Done in ${elapsed}s — ${newItems.length} new posts, ${detailCount} details written`);

  // ── IndexNow ──
  if (newSlugs.length > 0) {
    try {
      const urlList = [`${SITE_URL}/`, ...newSlugs.slice(0, 99).map(s => `${SITE_URL}/post/${s}`)];
      const res = await fetch("https://api.indexnow.org/indexnow", {
        method: "POST",
        headers: { "Content-Type": "application/json; charset=utf-8" },
        body: JSON.stringify({ host: SITE_HOST, key: INDEXNOW_KEY, keyLocation: `${SITE_URL}/${INDEXNOW_KEY}.txt`, urlList }),
      });
      console.log(`✅ IndexNow: ${urlList.length} URLs submitted (status ${res.status})`);
    } catch (err) {
      console.log(`⚠️  IndexNow failed: ${err.message}`);
    }
  }
}

main().catch(e => { console.error("Fatal error:", e.message); process.exit(1); });
