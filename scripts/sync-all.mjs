function cleanText(text) {
  if (!text) return "";
  let t = text;
  for (const pat of SOURCE_PATTERNS) t = t.replace(pat, SITE_NAME);
  // Remove doubled spaces, trailing dots from replacements
  return t.replace(/\s{2,}/g, " ").replace(/\s([,;.])/g, "$1").trim();
}

// De-duplicate doubled text (sarkariexam often doubles link labels)
function dedup(label) {
  if (!label) return "";
  const clean = label.trim();
  const half  = Math.floor(clean.length / 2);
  if (clean.length > 4 && clean.slice(0, half) === clean.slice(half)) return clean.slice(0, half).trim();
  return clean;
}

