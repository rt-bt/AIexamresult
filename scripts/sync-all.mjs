async function scrapeGenericDetail(url) {
  try {
    const html = await fetchHtml(url);
    const $ = cheerio.load(html);
    const rawTitle = $("h1").first().text().trim() || $("title").text().trim();
    const title = cleanCompetitorText(rawTitle);
    let publishedDate = $("meta[property='article:published_time']").attr("content") || $("time").attr("datetime") || "";
    if (publishedDate) {
      const d = new Date(publishedDate);
      if (!isNaN(d.getTime())) {
        if (d > new Date()) {
          publishedDate = "";
        } else {
          publishedDate = d.toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });
        }
      }
    }
    // Content search for real Post Date / Start Date if publishedDate is missing
    if (!publishedDate) {
      const pageText = $("body").text();
      const match = pageText.match(/Post\s*(?:Time|Date)\s*:\s*(\d{1,2}\s+[A-Za-z]+\s+\d{4})/i) ||
                    pageText.match(/(?:Online\s*Apply\s*Start\s*on|Apply\s*Start\s*Date|Start\s*Date)\s*[:\-]?\s*(\d{1,2}\s+[A-Za-z]+\s+\d{4})/i);
      if (match) {
        const d = new Date(match[1]);
        if (!isNaN(d.getTime()) && d <= new Date()) {
          publishedDate = d.toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });
        }
      }
    }
    let intro = $("meta[name='description']").attr("content") || "";
    if (intro.length < 10) intro = $("article p, .entry-content p, .post-content p").first().text().trim().slice(0, 300);
    if (!intro) intro = $("p").first().text().trim().slice(0, 300);
    intro = cleanCompetitorText(intro);

    const importantDates = [];
    const applicationFee = [];
    $("table").each((_, table) => {
      $(table).find("tr").each((_, row) => {
        const cells = $(row).find("td, th");
        if (cells.length >= 2) {
          const first = $(cells[0]).text().trim().toLowerCase();
          const second = $(cells[1]).text().trim();
          if (first && second) {
            if (first.includes("date") || first.includes("last") || first.includes("exam") || first.includes("admit")) importantDates.push($(cells[0]).text().trim() + " : " + second);
            if (first.includes("fee") || first.includes("general") || first.includes("obc") || first.includes("sc") || first.includes("st")) applicationFee.push($(cells[0]).text().trim() + " : " + second);
          }
        }
      });
    });

    const importantLinks = [];
    const seenLinkUrls = new Set();
    $("a[href]").each((_, link) => {
      const $link = $(link);
      const rawLabel = cleanLinkLabel($link.text().trim());
      const label = cleanCompetitorText(rawLabel);
      const href = $link.attr("href") || "";
      if (label && href && !isCompetitorLink(href, label) && !seenLinkUrls.has(href)) {
        const lower = label.toLowerCase();
        if (lower.includes("official") || lower.includes("apply") || lower.includes("download") || lower.includes("result") || lower.includes("admit") || lower.includes("answer") || lower.includes("website") || lower.includes("notification") || lower.includes("registration") || lower.includes("score")) {
          seenLinkUrls.add(href);
          importantLinks.push({ label, url: href });
        }
      }
    });

    const slug = generatePostSlug(url, title);
    return { title, slug, url, publishedDate, intro, importantDates, applicationFee, importantLinks, fullContentHtml: "" };
  } catch {
    return null;
  }
}

