function fetchHtmlFallback(url) {
  return new Promise((resolve, reject) => {
    const u = new URL(url);
    const mod = u.protocol === "https:" ? https : http;
    const req = mod.get(url, {
      headers: {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/125.0.0.0 Safari/537.36",
        Accept: "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "en-US,en;q=0.9",
      },
      timeout: FETCH_TIMEOUT,
    }, (res) => {
      let data = "";
      res.on("data", (chunk) => { data += chunk; });
      res.on("end", () => {
        if (res.statusCode !== 200 && res.statusCode !== 404) {
          return reject(new Error(`HTTP ${res.statusCode}`));
        }
        resolve(data);
      });
    });
    req.on("error", reject);
    req.on("timeout", () => { req.destroy(); reject(new Error("Timeout")); });
  });
}

async function fetchHtml(url) {
  // First try cloudscraper
  try {
    const html = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error("Timeout")), FETCH_TIMEOUT);
      cloudscraper({ uri: url, method: "GET" })
        .then((h) => { clearTimeout(timer); resolve(h); })
        .catch((err) => { clearTimeout(timer); reject(err); });
    });
    // Only fall back if page is clearly a Cloudflare-only challenge (not real content)
    if (html.length < 500 || (html.includes("Just a moment") && !html.includes("<!DOCTYPE")) || (html.includes("_cf_chl") && !html.includes("</html>"))) {
      return fetchHtmlFallback(url);
    }
    return html;
  } catch {
    return fetchHtmlFallback(url);
  }
}

// ======== Source 1: sarkariresult.com ========

async function scrapeSarkariResult() {
  const html = await fetchHtml("https://www.sarkariresult.com/");
  const $ = cheerio.load(html);

  const viewMorePaths = [];
  $("a.gb-button").each((_, a) => {
    const $a = $(a);
    if ($a.text().trim().toLowerCase() === "view more") {
      const href = $a.attr("href") || "";
      const path = href.replace(/https?:\/\/[^/]+\//, "").replace(/\/$/, "");
      viewMorePaths.push(path);
    }
  });

  const CATEGORY_MAP = { result: "results", admitcard: "admitCards", latestjob: "latestJobs", answerkey: "answerKeys", admission: "admissions" };
  const items = { results: [], admitCards: [], latestJobs: [], answerKeys: [], documents: [], admissions: [] };
  let containerIdx = 0;
  const seen = new Set();

  $("div[class*=gb-container]").each((_, el) => {
    const $el = $(el);
    const postLinks = $el.find("a[href]").filter((_, a) => $(a).text().trim().length > 15);
    if (postLinks.length < 3) return;

    const vmPath = viewMorePaths[containerIdx] || "";
    const category = CATEGORY_MAP[vmPath] || "";
    containerIdx++;

    if (!category) return;

    postLinks.each((_, a) => {
      const $a = $(a);
      const url = $a.attr("href") || "";
      if (!url || url.toLowerCase().includes(".pdf") || seen.has(url)) return;
      seen.add(url);
      const rawTitle = $a.text().trim();
      const title = cleanCompetitorText(rawTitle);
      if (isJunkOrSpam(title, url)) return;
      const properCat = categorizePost(title, category);
      const slug = generatePostSlug(url, title);
      if (items[properCat]) {
        items[properCat].push({ title, url, category: properCat, slug });
      }
    });
  });

  return items;
}

function cleanLinkLabel(label) {
  if (!label) return "";
  let clean = label.trim();
  const half = Math.floor(clean.length / 2);
  if (clean.length > 4 && clean.slice(0, half) === clean.slice(half)) {
    clean = clean.slice(0, half).trim();
  }
  return clean;
}

