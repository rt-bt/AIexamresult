import cloudscraper from "cloudscraper";
import * as cheerio from "cheerio";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_FILE = resolve(__dirname, "..", "data", "scraped-data.ts");
const JSON_FILE = resolve(__dirname, "..", "data", "scraped.json");
const POSTS_DIR = resolve(__dirname, "..", "data", "posts");
const SOURCE_HOME = "https://www.sarkariexam.com/";
const SOURCE_HOST = "www.sarkariexam.com";
const CATEGORIES = ["latestJobs", "admitCards", "answerKeys", "results", "admissions", "documents"];

const HEADING_MAP = {
  "result": "results",
  "exam result": "results",
  "new updates": "results",
  "admit card": "admitCards",
  "top online form": "latestJobs",
  "answer keys": "answerKeys",
  "answer key": "answerKeys",
  "admission form": "admissions",
  "document verification": "documents",
  "documents verification": "documents",
  "syllabus": "documents",
  "latest news": "results",
  "diploma / iti": "latestJobs",
  "b.tech / m.tech": "latestJobs",
};

function emptyData() {
  return {
    results: [],
    admitCards: [],
    latestJobs: [],
    answerKeys: [],
    documents: [],
    admissions: [],
    posts: {},
    fetchedAt: "",
  };
}

function loadData() {
  if (!existsSync(DATA_FILE)) return emptyData();
  const raw = readFileSync(DATA_FILE, "utf8");
  const jsonStr = raw
    .replace(/^\/\/.*[\r\n]+/gm, "")
    .replace(/^export const scrapedData = /, "")
    .replace(/\s*as const\s*;\s*$/, "")
    .replace(/;\s*$/, "");
  return JSON.parse(jsonStr);
}

function saveData(data) {
  data.fetchedAt = new Date().toISOString();
  const json = JSON.stringify(data, null, 2);
  writeFileSync(DATA_FILE, `// Auto-generated by clean sync - DO NOT EDIT\nexport const scrapedData = ${json};\n`, "utf8");
  writeFileSync(JSON_FILE, json, "utf8");
}

function sanitizeSlug(s) {
  return (s || "post")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-+|-+$/g, "") || "post";
}

function normalizeUrl(url) {
  try {
    const u = new URL(url, SOURCE_HOME);
    u.hash = "";
    return u.toString().replace(/\/$/, "");
  } catch {
    return "";
  }
}

function publicUrl(slug) {
  return `/post/${slug}`;
}

function cleanText(text) {
  return (text || "")
    .replace(/sarkari\s*exam/gi, "")
    .replace(/sarkariexam\.com/gi, "")
    .replace(/join\s+our\s+(whatsapp|telegram)\s+(channel|group)/gi, "")
    .replace(/download\s+mobile\s+app/gi, "")
    .replace(/\s+/g, " ")
    .trim();
}

function isSpamLabel(label) {
  const lower = cleanText(label).toLowerCase();
  return !lower ||
    lower.includes("whatsapp") ||
    lower.includes("telegram") ||
    lower.includes("facebook") ||
    lower.includes("instagram") ||
    lower.includes("youtube") ||
    lower.includes("mobile app") ||
    lower.includes("home page");
}

function isPublicLink(href) {
  if (!href || href === "#" || href.startsWith("javascript")) return false;
  try {
    const u = new URL(href, SOURCE_HOME);
    return u.hostname !== SOURCE_HOST && !u.hostname.includes("sarkariresult");
  } catch {
    return false;
  }
}

function categorizeByTitle(title, fallback) {
  const lower = title.toLowerCase();
  if (lower.includes("admit card") || lower.includes("hall ticket") || lower.includes("call letter") || lower.includes("exam city") || lower.includes("exam date")) return "admitCards";
  if (lower.includes("answer key") || lower.includes("response sheet")) return "answerKeys";
  if (lower.includes("admission") || lower.includes("counselling") || lower.includes("counseling")) return "admissions";
  if (lower.includes("result") || lower.includes("merit list") || lower.includes("cut off") || lower.includes("cutoff")) return "results";
  if (lower.includes("document") || lower.includes("certificate") || lower.includes("pan ") || lower.includes("aadhar") || lower.includes("aadhaar")) return "documents";
  if (lower.includes("online form") || lower.includes("apply") || lower.includes("recruitment") || lower.includes("apprentice") || lower.includes("vacancy") || lower.includes("job")) return "latestJobs";
  return fallback || "latestJobs";
}

async function fetchHtml(url) {
  return cloudscraper({
    uri: url,
    method: "GET",
    headers: {
      "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/125 Safari/537.36",
      "Accept-Language": "en-US,en;q=0.9",
    },
  });
}

async function scrapeListings() {
  const html = await fetchHtml(SOURCE_HOME);
  const $ = cheerio.load(html);
  const items = [];
  const seen = new Set();

  $(".below-block").each((_, block) => {
    const $block = $(block);
    const heading = cleanText($block.find("h4.wp-block-heading, h4").first().text()).toLowerCase();
    const fallback = HEADING_MAP[heading];
    if (!fallback) return;

    $block.find("ul.wp-block-latest-posts__list li a.wp-block-latest-posts__post-title, a[href]").each((__, link) => {
      const href = normalizeUrl($(link).attr("href") || "");
      const title = cleanText($(link).text());
      if (!href || !title || title.length < 12 || seen.has(href)) return;
      seen.add(href);
      const slug = sanitizeSlug(new URL(href).pathname.split("/").filter(Boolean).pop() || title);
      items.push({ title, sourceUrl: href, url: publicUrl(slug), category: categorizeByTitle(title, fallback), slug });
    });
  });

  return items.filter((item) => CATEGORIES.includes(item.category));
}

async function scrapeDetail(item) {
  try {
    const html = await fetchHtml(item.sourceUrl);
    const $ = cheerio.load(html);
    const publishedDate = $("time.entry-date.published").attr("datetime") || $("time").first().attr("datetime") || "";
    const intro = cleanText($("div.post-desc p").text() || $("div.entry-content p").first().text() || "");
    const importantDates = [];
    const applicationFee = [];

    $("div.newtable1 h3, table h3").each((_, h) => {
      const $h = $(h);
      const sectionTitle = cleanText($h.text()).toLowerCase();
      const lines = [];
      $h.closest("td, div, table").find("li").each((__, li) => {
        const text = cleanText($(li).text());
        if (text) lines.push(text);
      });
      if (sectionTitle.includes("important dates")) importantDates.push(...lines);
      if (sectionTitle.includes("application fee")) applicationFee.push(...lines);
    });

    if (importantDates.length === 0) {
      $("table tr").each((_, row) => {
        const cells = $(row).find("td, th");
        if (cells.length < 2) return;
        const first = cleanText($(cells[0]).text());
        const second = cleanText($(cells[1]).text());
        const lower = first.toLowerCase();
        if (first && second && (lower.includes("date") || lower.includes("last") || lower.includes("exam") || lower.includes("admit"))) {
          importantDates.push(`${first}: ${second}`);
        }
      });
    }

    const importantLinks = [];
    $("div.newtable2 table tr, table tr").each((_, row) => {
      const label = cleanText($(row).find("td").first().text());
      const href = $(row).find("a[href]").first().attr("href") || "";
      if (!isSpamLabel(label) && isPublicLink(href)) {
        importantLinks.push({ label, url: new URL(href, SOURCE_HOME).toString() });
      }
    });

    if (importantLinks.length === 0) {
      $("a[href]").each((_, link) => {
        const label = cleanText($(link).text());
        const href = $(link).attr("href") || "";
        if (!isSpamLabel(label) && isPublicLink(href)) {
          importantLinks.push({ label, url: new URL(href, SOURCE_HOME).toString() });
        }
      });
    }

    return {
      title: item.title,
      slug: item.slug,
      url: publicUrl(item.slug),
      category: item.category,
      publishedDate,
      intro,
      importantDates: [...new Set(importantDates.map(cleanText).filter(Boolean))],
      applicationFee: [...new Set(applicationFee.map(cleanText).filter(Boolean))],
      importantLinks: importantLinks.slice(0, 12),
      fullContentHtml: "",
    };
  } catch {
    return {
      title: item.title,
      slug: item.slug,
      url: publicUrl(item.slug),
      category: item.category,
      publishedDate: "",
      intro: "",
      importantDates: [],
      applicationFee: [],
      importantLinks: [],
      fullContentHtml: "",
    };
  }
}

async function main() {
  console.log("AI Exam Result clean sync started");
  const existing = loadData();
  const knownSlugs = new Set();
  for (const category of CATEGORIES) {
    for (const item of existing[category] || []) knownSlugs.add(item.slug);
  }

  const fresh = await scrapeListings();
  console.log(`Found ${fresh.length} fresh listing items`);

  mkdirSync(POSTS_DIR, { recursive: true });
  let added = 0;
  let updated = 0;

  for (const item of fresh) {
    const publicItem = {
      title: item.title,
      url: publicUrl(item.slug),
      category: item.category,
      slug: item.slug,
    };

    const bucket = existing[item.category] || [];
    const index = bucket.findIndex((old) => old.slug === item.slug || old.title.toLowerCase() === item.title.toLowerCase());
    if (index === -1) {
      bucket.unshift(publicItem);
      added++;
    } else {
      bucket[index] = { ...bucket[index], ...publicItem };
      updated++;
    }
    existing[item.category] = bucket;

    const detail = await scrapeDetail(item);
    existing.posts[item.slug] = {
      lastDate: detail.importantDates.find((d) => d.toLowerCase().includes("last"))?.replace(/^.*?:/, "").trim(),
    };
    writeFileSync(resolve(POSTS_DIR, `${item.slug}.json`), JSON.stringify(detail, null, 2), "utf8");
  }

  for (const category of CATEGORIES) {
    existing[category] = (existing[category] || []).slice(0, 500);
  }
  saveData(existing);
  console.log(`Clean sync complete. Added: ${added}, Updated: ${updated}`);
}

main().catch((error) => {
  console.error("Clean sync failed:", error.message);
  process.exit(1);
});
