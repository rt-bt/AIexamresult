import cloudscraper from "cloudscraper";
import * as cheerio from "cheerio";
import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_FILE = resolve(__dirname, "..", "data", "scraped-data.ts");
const POSTS_DIR = resolve(__dirname, "..", "data", "posts");

function loadData() {
  const raw = readFileSync(DATA_FILE, "utf8");
  const jsonStr = raw
    .replace(/^\/\/.*[\r\n]+/, "")
    .replace(/^export const scrapedData = /, "")
    .replace(/\s*as const\s*;\s*$/, "")
    .replace(/;\s*$/, "");
  return JSON.parse(jsonStr);
}

function saveData(data) {
  const ts = `// Auto-generated by sync-sarkariresult - DO NOT EDIT\nexport const scrapedData = ${JSON.stringify(data, null, 2)};\n`;
  writeFileSync(DATA_FILE, ts, "utf8");
}

function sanitizeSlug(s) {
  return s.replace(/[<>:"/\\|?*]+/g, "-").replace(/-+/g, "-").replace(/^-+|-+$/g, "") || "post";
}

function fetchHtml(url) {
  return cloudscraper({ uri: url, method: "GET" });
}

async function scrapeSarkariResult() {
  const html = await fetchHtml("https://www.sarkariresult.com/");
  const $ = cheerio.load(html);

  // Get "View More" buttons for category ordering
  const viewMorePaths = [];
  $("a.gb-button").each((_, a) => {
    const $a = $(a);
    if ($a.text().trim().toLowerCase() === "view more") {
      const href = $a.attr("href") || "";
      const path = href.replace(/https?:\/\/[^/]+\//, "").replace(/\/$/, "");
      viewMorePaths.push(path);
    }
  });

  const CATEGORY_MAP = { result: "results", admitcard: "admitCards", latestjob: "latestJobs", answerkey: "answerKeys", admission: "admissions" };
  const items = { results: [], admitCards: [], latestJobs: [], answerKeys: [], documents: [], admissions: [] };
  let containerIdx = 0;
  const seen = new Set();

  $("div[class*=gb-container]").each((_, el) => {
    const $el = $(el);
    const postLinks = $el.find("a[href]").filter((_, a) => $(a).text().trim().length > 15);
    if (postLinks.length < 3) return;

    const vmPath = viewMorePaths[containerIdx] || "";
    const category = CATEGORY_MAP[vmPath] || "";
    containerIdx++;

    if (!category) return;

    postLinks.each((_, a) => {
      const $a = $(a);
      const url = $a.attr("href") || "";
      if (!url || seen.has(url)) return;
      seen.add(url);
      const title = $a.text().trim();
      const slug = url.replace(/\/$/, "").split("/").pop() || title.toLowerCase().replace(/[^a-z0-9]+/g, "-");
      items[category].push({ title, url, category, slug });
    });
  });

  return items;
}

async function scrapePostDetail(url) {
  try {
    const html = await fetchHtml(url);
    const $ = cheerio.load(html);

    const title = $("h1").first().text().trim() || $("title").text().trim();
    const slug = url.replace(/\/$/, "").split("/").pop().replace(/\.html?$/, "") || "post";

    let publishedDate = $("meta[property='article:published_time']").attr("content") || "";
    if (publishedDate) {
      const d = new Date(publishedDate);
      if (!isNaN(d.getTime())) {
        publishedDate = d.toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });
      }
    }

    let intro = "";
    $("h3, strong, b").each((_, el) => {
      const text = $(el).text().trim().toLowerCase();
      if (text.includes("short information") || text.includes("brief information")) {
        intro = $(el).parent().next("p").text().trim() || $(el).closest("div").find("p").first().text().trim();
      }
    });
    if (!intro) intro = $(".entry-content p").first().text().trim().slice(0, 300);

    const importantDates = [];
    $("table").each((_, table) => {
      const $table = $(table);
      $table.find("tr").each((_, row) => {
        const cells = $(row).find("td, th");
        if (cells.length >= 2) {
          const first = $(cells[0]).text().trim().toLowerCase();
          const second = $(cells[1]).text().trim();
          if (first && second && (first.includes("date") || first.includes("fee") || first.includes("age") || first.includes("exam") || !first.includes("link"))) {
            importantDates.push($(cells[0]).text().trim() + " : " + second);
          }
        }
      });
    });

    const importantLinks = [];
    $("table a, .entry-content a").each((_, link) => {
      const $link = $(link);
      const label = $link.text().trim();
      const href = $link.attr("href") || "";
      if (label && href && href !== "#" && !href.startsWith("javascript")) {
        importantLinks.push({ label, url: href });
      }
    });

    return { title, slug, url, publishedDate, intro, importantDates, applicationFee: [], importantLinks, fullContentHtml: "" };
  } catch {
    return null;
  }
}

async function main() {
  console.log("Loading existing data...");
  const existing = loadData();
  const existingUrls = new Set();

  for (const key of ["results", "admitCards", "latestJobs", "answerKeys", "documents", "admissions"]) {
    for (const item of (existing[key] || [])) {
      if (item.url) existingUrls.add(item.url.replace(/\/$/, ""));
    }
  }

  console.log("Fetching sarkariresult.com listings...");
  const freshData = await scrapeSarkariResult();

  let newCount = 0;
  for (const cat of ["results", "admitCards", "latestJobs", "answerKeys", "documents", "admissions"]) {
    const freshItems = freshData[cat] || [];
    const existingItems = existing[cat] || [];
    for (const item of freshItems) {
      const url = item.url.replace(/\/$/, "");
      if (!existingUrls.has(url)) {
        existingItems.push(item);
        newCount++;
      }
    }
  }

  console.log("New items from sarkariresult.com: " + newCount);

  if (newCount > 0) {
    mkdirSync(POSTS_DIR, { recursive: true });
    let detailCount = 0;

    for (const cat of ["results", "admitCards", "latestJobs", "answerKeys", "documents", "admissions"]) {
      for (const item of (existing[cat] || [])) {
        if (item._processed) continue;
        const url = item.url.replace(/\/$/, "");
        if (existingUrls.has(url)) continue;
        existingUrls.add(url);
        item._processed = true;

        const post = await scrapePostDetail(item.url);
        if (post) {
          const slug = sanitizeSlug(post.slug);
          post.slug = slug;
          if (!existing.posts) existing.posts = {};
          existing.posts[slug] = post;
          writeFileSync(POSTS_DIR + "/" + slug + ".json", JSON.stringify(post, null, 2), "utf8");
          detailCount++;
        }
      }
    }

    existing.fetchedAt = new Date().toISOString();
    saveData(existing);
    console.log("Added " + newCount + " new items, scraped " + detailCount + " details");
    console.log("Updated data/scraped-data.ts");
  } else {
    console.log("Data is already up to date.");
  }
}

main().catch((e) => { console.error("Error:", e.message); process.exit(1); });
